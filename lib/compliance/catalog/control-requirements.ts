import type { CatalogControlMapping } from "./types";

// Synergie-Kanten: welches Common Control erfüllt welche Anforderung in
// welchem Rahmenwerk — voll oder teilweise. Jede Anforderung mit
// legalStatus ≠ repealed braucht ≥ 1 Kante (Test catalog-shape).
//
// Kompakte Schreibweise: m(control, requirement, coverage?, note?).

type Cov = "full" | "partial";
const m = (
	control: string,
	requirement: `${string}:${string}`,
	coverage: Cov = "full",
	note?: string,
): CatalogControlMapping => ({ control, requirement, coverage, note });

// Mehrere Anforderungen desselben Rahmenwerks für ein Control.
const many = (
	control: string,
	framework: string,
	codes: string[],
	coverage: Cov = "full",
): CatalogControlMapping[] =>
	codes.map((code) => m(control, `${framework}:${code}`, coverage));

