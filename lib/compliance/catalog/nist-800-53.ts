function policy(
	section: string,
	title: string,
	topic: string,
	domain: Spec["domain"],
	controls: string[],
): Spec {
	return {
		code: `${section}-1`,
		section,
		title,
		text: `Eine Richtlinie ${topic} und Verfahren zu ihrer Umsetzung festlegen, verteilen und eine verantwortliche Person benennen; beides wird in festgelegten Abständen und nach Anlässen überprüft.`,
		domain,
		controls,
		variants: L,
		evidence: ["Richtlinie mit Freigabe", "Verfahrensbeschreibung"],
	};
}

