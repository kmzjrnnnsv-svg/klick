// Microsoft Supplier Security and Privacy Assurance (SSPA): Programm, mit dem
// Microsoft Lieferanten prüft, die personenbezogene oder vertrauliche Daten
// von Microsoft verarbeiten. Grundlage sind die Microsoft Supplier Data
// Protection Requirements (DPR), Stand nach Modellwissen Fassung 10 (2024)
// mit Abschnitt zu KI-Systemen. Jährliche Selbstprüfung im SSPA-Portal, je
// nach Datenprofil zusätzlich unabhängige Prüfung oder Zertifikat. Eigene
// Formulierung nach Modellwissen, gegen die aktuelle DPR-Fassung von
// Microsoft prüfen. Nummern sind eigene je Abschnitt (`MGT.1` …), nicht die
// fortlaufenden DPR-Nummern, weil die Zuordnung nicht sicher ist.
// Varianten nach Datenprofil: bei personenbezogenen Daten gelten alle
// Abschnitte, bei nur vertraulichen Daten Verwaltung, Vorfälle, Sicherheit,
// Rückgabe am Vertragsende und KI (KI nur, wenn der Lieferant KI einsetzt).

